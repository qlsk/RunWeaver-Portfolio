public enum ParameterType
{
    DamageBonus, // 공격 피해량 증가량
    AttackSpeedBonus, // 공격 속도 증가량
    ElementalReactionDamageBonus, // 원소 반응 대미지 증가량
    RequiredAttackCount, // 필요 공격 횟수
    EchoDamageRatio, // 추가 탄환 피해량 비율
    MarkDurationSeconds, // 표식 지속 시간
    MarkedTargetDamageBonus, // 표식 피해량 증가량
    DashDistanceBonus, // 대시 거리 증가량
    CooldownReduction, // 재사용 대기시간 감소량
    DamageReduction, // 받는 피해량 감소량
    DurationSeconds, // 효과 지속 시간(초)
    DashDamageRatio, // 대시 피해량 비율
    NextAttackDamageBonus, // 다음 공격 피해량 증가량
    TriggerWindowSeconds, // 발동 조건을 충족할 수 있는 시간(초)
    ShieldCapacityBonus, // 보호막 흡수량 증가량
    DurationBonusSeconds, // 지속 시간 증가량(초)
    ReflectedDamageRatio, // 반사 피해량 비율
    BurstRadius, // 폭발 반경
    KnockbackDistance, // 넉백 거리
    MovementSpeedBonus, // 이동 속도 증가량
    ImmunityDurationSeconds, // 면역 지속 시간(초)
    MaxHealthHealRatio, // 최대 체력 대비 회복량 비율
    CurrentCastCooldownReduction, // 현재 시전의 재사용 대기시간 감소량
    WaveDamageRatio, // 파동 피해량 비율
    WaveRadius // 파동 반경
}
